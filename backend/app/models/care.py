import uuid
from datetime import date

from sqlalchemy import JSON, Boolean, Date, ForeignKey, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, TimestampMixin, uuid_pk


class CarePlan(Base, TimestampMixin):
    """The patient's follow-up plan, written by the prescribing doctor.

    Everything here is the doctor's own advice (diet, activity, tests, follow-up);
    nothing is generated by a model.
    """

    __tablename__ = "care_plans"

    id: Mapped[uuid.UUID] = uuid_pk()
    patient_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("patients.id", ondelete="CASCADE"), index=True, nullable=False
    )
    doctor_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("doctors.id", ondelete="SET NULL")
    )
    record_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("records.id", ondelete="SET NULL")
    )
    # {"note": str|None, "more": [str], "less": [str]}
    diet: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    activity: Mapped[list] = mapped_column(JSON, nullable=False, default=list)
    # [{"name": str, "due": "YYYY-MM-DD"}]
    tests: Mapped[list] = mapped_column(JSON, nullable=False, default=list)
    follow_up_date: Mapped[date | None] = mapped_column(Date)
    notes: Mapped[str | None] = mapped_column(String(1000))
    active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)


class CareLog(Base, TimestampMixin):
    """One tick on the patient's daily checklist (medicine taken, walk done...)."""

    __tablename__ = "care_logs"
    __table_args__ = (UniqueConstraint("patient_id", "item_key", "log_date"),)

    id: Mapped[uuid.UUID] = uuid_pk()
    patient_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("patients.id", ondelete="CASCADE"), index=True, nullable=False
    )
    item_key: Mapped[str] = mapped_column(String(120), nullable=False)
    log_date: Mapped[date] = mapped_column(Date, nullable=False)
    done: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
